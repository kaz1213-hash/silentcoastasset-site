'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const registry = JSON.parse(fs.readFileSync(path.join(root, 'commerce/products.json'), 'utf8'));
const source = fs.readFileSync(path.join(root, 'commerce/commerce.js'), 'utf8');
const item = registry.products.find(p => p.id === 'tanuki-security-android');
assert.ok(item && item.enabled && item.group === 'available');
assert.equal(item.price_label_ja, '日本 ¥500・買い切り');
assert.equal(registry.products.filter(p => p.id === item.id).length, 1);
const patched = source.replace('  function checkoutUrl(product, lang) {', '  globalThis.testCheckout = isSafeCheckoutUrl; return;\n  function checkoutUrl(product, lang) {');
assert.notEqual(patched, source);
const ctx = { URL };
vm.runInNewContext(patched, ctx);
for (const u of [item.checkout_url_ja, item.checkout_url_en, 'https://apps.microsoft.com/detail/9NHDT5BNC31K']) assert.equal(ctx.testCheckout(u), true, u);
for (const u of ['http://play.google.com/store/apps/details?id=jp.silentcoast.tanukisecurity','https://play.google.com.evil.example/store/apps/details?id=jp.silentcoast.tanukisecurity','https://play.google.com/store/apps/details?id=other','https://play.google.com/store/apps/details?id=jp.silentcoast.tanukisecurity&id=other','https://play.google.com/store/apps/details?id=jp.silentcoast.tanukisecurity&redirect=evil','https://play.google.com/store/apps/other?id=jp.silentcoast.tanukisecurity']) assert.equal(ctx.testCheckout(u), false, u);
console.log('ANDROID_SECURITY_SHELF_PASS');
