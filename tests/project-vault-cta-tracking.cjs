'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'project-vault.html'), 'utf8');
const toml = fs.readFileSync(path.join(root, 'netlify.toml'), 'utf8');
const protectedManifest = JSON.parse(fs.readFileSync(path.join(root, 'release', 'protected-files.json'), 'utf8'));
const canonicalStore = 'https://chromewebstore.google.com/detail/project-vault-for-chatgpt/lnndbebmjnklgammhjmgpdaijdcmighl';
const count = (haystack, needle) => haystack.split(needle).length - 1;
assert.equal(count(html, 'href="/go/project-vault"'), 2, 'Both JP and EN primary CTA links must use click hop');
assert.equal(count(html, 'href="' + canonicalStore + '"'), 0, 'Direct CTA links must not bypass click hop');
assert.ok(count(html, 'target="_blank" rel="noopener noreferrer"') >= 2, 'Keep safe links and new tab');
const sections = toml.split('[[redirects]]').slice(1);
const matching = sections.filter(s => s.includes('from = "/go/project-vault"'));
assert.equal(matching.length, 1, 'Exactly one Project Vault redirect');
assert.ok(matching[0].includes('to = "' + canonicalStore + '"'), 'Redirect must use canonical Store listing');
assert.ok(matching[0].includes('status = 302'), 'Temporary redirect, not cached permanent 301');
assert.ok(matching[0].includes('force = true'), 'Avoid static shadowing');
const digest = crypto.createHash('sha256').update(html.replace(/\r\n?/g, '\n')).digest('hex');
assert.equal(digest, protectedManifest.protected['project-vault.html'], 'Preserve release scope protection');
console.log('CTA_TRACKING_ROUTE_PASS 2/2 bilingual links, Netlify 302, protected hash, unchanged Store destination');
